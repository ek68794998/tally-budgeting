"""Generates seed.dev.sql: made-up dev transactions for the last 24 months, relative to today."""
import random
from pathlib import Path

MONTHS = 24
random.seed(68)
q = lambda s: "NULL" if s is None else "'" + s.replace("'", "''") + "'"

assets = [("Stark Industries Checking","liquid_asset","chase"),("Wakanda Savings","liquid_asset",None),
          ("Avengers Rewards Card","short_term_liability","apple"),("Pym Particle 401k","fixed_asset","fidelity")]
# (label, budget cents, frequency months, budget type, description)
cats = {
 "Food": [("Groceries",60000,1,"expense","Grocery store food and home supplies"),("Restaurants",30000,1,"expense",None)],
 "Home": [("Rent",240000,1,"expense","Apartment or house rental expenses"),("Utilities",20000,1,"expense",None)],
 "Transport": [("Gas",12000,1,"expense","Gas for cars, hover jets, or whatever Stark needs"),("Subway",13000,1,"expense",None)],
 "Fun": [("Entertainment",15000,1,"expense","Movies and events"),("Shopping",25000,1,"expense",None)],
 "Income": [("Paycheck",450000,1,"income","Income from work"),("Refunds",0,1,"neutral",None)],
}
# (merchant, subcategory, min cents, max cents, weight)
spend = [
 ("Delmars Deli-Grocery","Groceries",400,2500,5),("Target","Groceries",900,9000,3),("Trader Joe's Astoria","Groceries",2500,9500,3),
 ("Prachya Thai","Restaurants",3000,8000,2),("Coney Island Hot Dogs","Restaurants",600,1800,2),("Shake Shack Madison Sq","Restaurants",1200,3200,2),
 ("Citi Bike","Subway",400,1900,2),("MTA Subway","Subway",290,2900,3),("Shell Queens Blvd","Gas",3000,6500,1),
 ("Lincoln Memorial Gift Shop","Shopping",1500,9000,1),("Apple Services","Entertainment",299,1599,1),("Sanctum Sanctorum Tours","Entertainment",2500,7500,1),
 ("Stark Expo Tickets","Entertainment",4500,12000,1),("Daily Planet Newsstand","Shopping",300,1500,1),("Kamar-Taj Yoga","Entertainment",2000,4500,1),
]
notes_pool = ["Split with Pepper","Birthday gift for Bucky","Reimbursable by SHIELD","Late-night run after patrol","Tony's treat, paying him back",
 "Date night with Gwen","Bought in bulk for the team","Price jumped again","Used coupon from Nick Fury","Needed it for the Quinjet"]
accts=[1,1,1,2,3,3,None]

rows=[]
def add(k,dom,m,sub,cents,direction="debit",acct=None,notes=None,one=False,hap=2):
    rows.append((k,dom,m,sub,cents,direction,acct,notes,one,hap))

weighted=[s for s in spend if s[4]>0 for _ in range(s[4])]
for k in range(MONTHS-1,-1,-1):
    day=lambda lo=1,hi=28: random.randint(lo,hi)
    add(k,1,"Avengers Mansion Landlord","Rent",240000,acct=1)
    add(k,day(10,15),"ConEd Electric","Utilities",random.randint(6000,14000),acct=1)
    for dom in (1,15):
        add(k,dom,"Stark Industries Payroll","Paycheck",random.randint(205000,225000),"credit",1,hap=3)
    for _ in range(14):
        m,sub,lo,hi,_w=random.choice(weighted)
        note=random.choice(notes_pool) if random.random()<.3 else None
        add(k,day(),m,sub,random.randint(lo,hi),"debit",random.choice(accts),note,False,random.choice([1,2,2,3]))
    add(k,day(),random.choice(["Stark Expo Tickets","Sanctum Sanctorum Tours","Lincoln Memorial Gift Shop"]),random.choice(["Entertainment","Shopping"]),
        random.randint(15000,80000),"debit",random.choice([1,3]),random.choice(notes_pool),True,random.choice([1,3]))
    if random.random()<.6:
        add(k,day(),"Avengers Tower Furniture","Shopping",random.randint(20000,90000),"debit",3,None,True,random.choice([1,2,3]))
    if random.random()<.4:
        add(k,day(),"Apple.com/us (return)","Refunds",random.randint(1000,30000),"credit",3,random.choice(notes_pool),False,2)
    if random.random()<.3:
        add(k,day(),"Quinjet Fuel Co","Gas",random.randint(5000,9000),"debit",None,None,False,1)
    if random.random()<.25:
        add(k,day(),"Hawkeye Archery Range","Entertainment",random.randint(2000,5000),"debit",2,None,True,3)

o=[f"""-- Dev seed data: ~20 made-up transactions per month for the last {MONTHS} months, relative to today.
-- Generated by seed.py; edit that and regenerate rather than editing this file.
-- Run against an empty database; transactions are not deduplicated on re-run.""","BEGIN;"]
for n,t,p in assets:
    o.append(f"INSERT INTO asset (name,type,value_cents,provider,active) VALUES ({q(n)},{q(t)},{random.randint(10000,9000000)*(-1 if 'liab' in t else 1)},{q(p)},{'false' if n.startswith('Pym') else 'true'}) ON CONFLICT (name) DO NOTHING;")
for c,subs in cats.items():
    o.append(f"INSERT INTO category (label) VALUES ({q(c)}) ON CONFLICT (label) DO NOTHING;")
    for s,b,f,bt,desc in subs:
        needs=50 if c in("Home","Food","Transport") else 10
        o.append(f"INSERT INTO subcategory (label,category,description,budget_amount_cents,budget_frequency_months,budget_type,pct_needs,pct_savings) "
                 f"SELECT {q(s)},id,{q(desc)},{b},{f},{q(bt)},{needs},{0 if bt!='income' else 20} FROM category WHERE label={q(c)} ON CONFLICT (label) DO NOTHING;")
for k,dom,m,sub,cents,dirn,acct,notes,one,hap in rows:
    a="NULL" if acct is None else f"(SELECT id FROM asset WHERE name={q(assets[acct-1][0])})"
    when=f"(LEAST((date_trunc('month', current_date) - interval '{k} months')::date + {dom-1}, current_date) + time '12:00') AT TIME ZONE 'UTC'"
    o.append(f"INSERT INTO txn (merchant,date,account,subcategory,amount_cents,direction,happiness,notes,one_time) VALUES "
             f"({q(m)},{when},{a},(SELECT id FROM subcategory WHERE label={q(sub)}),{cents},{q(dirn)},{hap},{q(notes)},{str(one).lower()});")
o.append("COMMIT;")
Path(__file__).with_name("seed.dev.sql").write_text("\n".join(o)+"\n")
print(len(rows))
